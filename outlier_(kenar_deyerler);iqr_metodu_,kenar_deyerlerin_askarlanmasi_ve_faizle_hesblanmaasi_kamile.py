plt.show()
#boxplot mavi qutu esas gostericiler qara xett median ortadaki reqem,yan xettler meafe,noqteler digerlerinden  cox ferqlenen reqemlerdir,burda ise sag qanad soldan daha da
#irelidir

Q1=df["training_hours"].quantile(0.25)
Q3=df["training_hours"].quantile(0.75)
IQR=Q3-Q1
print("Q1:",Q1)#25%
print("Q3:",Q3)#75%
print("IQR:",IQR)#ARASINDAKI mesafeni gosterir
#burda Q3 daha yuksekdir demeli asagida cixirsan Q1 23 -Q3 88 =IQR 65 bele ,yeni mesabesi cixilanda iqr onda cavabi tapilir

lower_limit=Q1-1.5*IQR
upper_limit=Q3+1.5*IQR
print("Asagi limit:",lower_limit)
print("Yuxari limit:",upper_limit)
#bu asagi ve yuxari hesablanir

outliers=df[(df["training_hours"]<lower_limit) | (df["training_hours"]>upper_limit)]#outliers yeni sag sol outiler demekdir,
#I olan ise ve ya demekdir ortada duran xeti deyirem
print(outliers[["training_hours"]])
#33 baslayib 19145 indeks sira nomresidir iscilerin sol terefdeki,sag ise iscilerin saat reqemler dir 206 basliyir 190 bitir.bu en cox muellime,telimci ,isci saatlri
#birde meselen satis islerinde ve s

outlier_count=len(outliers)
print("Outlier sayi:",outlier_count)
#len cedvelde melumat sayisi funksiya,outlier count saydigimiz yadda saxlayir

total_workers=len(df)
outlier_percentage=(len(outliers)/total_workers)*100
print("Outlier faizi:",outlier_percentage)
#len sirketdeki butun iscilerin faizi hesablanir
#len outlierskenar gostericeleri sayir
